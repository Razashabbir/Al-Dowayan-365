function translate(text) {
  const t = text.trim()
  if (!t || !/[A-Za-z]/.test(t)) return null
  let out = AR[t]
  if (out == null) {
    for (const [re, fn] of PATTERNS) {
      const m = t.match(re)
      if (m) { out = fn(m); break }
    }
  }
  if (out == null && t.includes(', ')) {           // e.g. "Still needed" list
    const parts = t.replace(/\.$/, '').split(', ').map((p) => AR[p])
    if (parts.every(Boolean)) out = parts.join('، ') + (t.endsWith('.') ? '.' : '')
  }
  return out == null ? null : text.replace(t, out)
}

const SKIP = 'script,style,textarea,code,[data-no-tr]'
const ATTRS = ['placeholder', 'title', 'aria-label']

function translateNode(node) {
  if (node.nodeType === 3) {
    const p = node.parentElement
    if (!p || p.closest(SKIP)) return
    const out = translate(node.nodeValue)
    if (out != null && out !== node.nodeValue) node.nodeValue = out
    return
  }
  if (node.nodeType !== 1 || node.closest(SKIP)) return
  for (const el of [node, ...node.querySelectorAll('*')]) {
    if (el.closest(SKIP)) continue
    for (const a of ATTRS) {
      const v = el.getAttribute(a)
      if (v) { const out = translate(v); if (out != null && out !== v) el.setAttribute(a, out) }
    }
  }
  const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT)
  for (let n = walker.nextNode(); n; n = walker.nextNode()) translateNode(n)
}

let observer = null

/** Start (lang = 'ar') or stop translating. Stopping relies on the app re-rendering in English. */
export function setPageLanguage(lang) {
  const html = document.documentElement
  html.lang = lang
  html.dir = lang === 'ar' ? 'rtl' : 'ltr'
  if (observer) { observer.disconnect(); observer = null }
  if (lang !== 'ar') return
  const run = () => translateNode(document.body)
  run()
  observer = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') translateNode(m.target)
      else if (m.type === 'attributes') translateNode(m.target)
      else m.addedNodes.forEach(translateNode)
    }
  })
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS })
}

